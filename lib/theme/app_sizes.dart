/// Spacing, radius, icon and font-size scale.
/// Sizes below are tuned for the Press Start 2P pixel font.
class AppSizes {
  AppSizes._();

  // ---------- Spacing (8pt grid) ----------
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;

  static const double screenPaddingH = 24;
  static const double screenPaddingV = 16;

  // ---------- Radii ----------
  static const double radiusSm = 8;
  static const double radiusMd = 14;
  static const double radiusLg = 20;
  static const double radiusXl = 28;
  static const double radiusPill = 999;

  // ---------- Component sizes ----------
  static const double buttonHeight = 54;
  static const double buttonHeightSm = 44;
  static const double inputHeight = 58;
  static const double appBarHeight = 56;

  // ---------- Icons ----------
  static const double iconSm = 16;
  static const double iconMd = 22;
  static const double iconLg = 30;
  static const double iconXl = 44;

  // ---------- Font sizes (pixel font scale) ----------
  static const double fontXs = 8; // tiny labels
  static const double fontSm = 9; // captions
  static const double fontMd = 10; // standard body
  static const double fontLg = 11; // emphasized body
  static const double fontXl = 12; // h3 / small headings
  static const double fontXxl = 14; // h1 / h2
  static const double fontDisplay = 18; // hero
}
